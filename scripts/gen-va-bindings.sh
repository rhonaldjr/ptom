#!/usr/bin/env bash
# Regenerates crates/farsight-gpu-sys/src/va/bindings.rs: Rust declarations
# for the parts of libva (VA-API 1.22 headers, MIT licence) the hardware
# encoder uses. The library itself is loaded at run time, so builds need
# neither libva nor clang; only this script does. Runs in the builder image.
set -euo pipefail
cd "$(dirname "$0")/.."
exec docker run --rm -u "$(id -u):$(id -g)" -v "$PWD":/w -w /w \
  -e CARGO_HOME=/w/target-docker/.cargo farsight-builder bash -euo pipefail -c '
  version=2.22.0 api=1.22.0
  sha256=467c418c2640a178c6baad5be2e00d569842123763b80507721ab87eb7af8735
  work="$(mktemp -d)"
  curl -sSfL -o "$work/libva.tar.gz" "https://github.com/intel/libva/archive/refs/tags/$version.tar.gz"
  echo "$sha256  $work/libva.tar.gz" | sha256sum -c --quiet
  tar -xzf "$work/libva.tar.gz" -C "$work"
  inc="$work/libva-$version"
  IFS=. read -r major minor micro <<<"$api"
  sed -e "s/@VA_API_MAJOR_VERSION@/$major/" -e "s/@VA_API_MINOR_VERSION@/$minor/" \
      -e "s/@VA_API_MICRO_VERSION@/$micro/" -e "s/@VA_API_VERSION@/$api/g" \
      "$inc/va/va_version.h.in" > "$inc/va/va_version.h"
  printf "#include <va/va.h>\n#include <va/va_drm.h>\n#include <va/va_enc_h264.h>\n" > "$work/wrapper.h"
  bindgen=target-docker/.cargo/bin/bindgen
  [ -x "$bindgen" ] || cargo install --quiet --locked bindgen-cli --version 0.71.1
  out=crates/farsight-gpu-sys/src/va/bindings.rs
  "$bindgen" "$work/wrapper.h" \
    --dynamic-loading Libva --dynamic-link-require-all \
    --allowlist-function "va(GetDisplayDRM|Initialize|Terminate|QueryConfigEntrypoints|GetConfigAttributes|CreateConfig|DestroyConfig|CreateSurfaces|DestroySurfaces|CreateContext|DestroyContext|CreateBuffer|DestroyBuffer|MapBuffer|UnmapBuffer|BeginPicture|RenderPicture|EndPicture|SyncSurface|CreateImage|DestroyImage|PutImage|ErrorStr)" \
    --allowlist-type "VA(EncSequenceParameterBufferH264|EncPictureParameterBufferH264|EncSliceParameterBufferH264|EncMiscParameterBuffer|EncMiscParameterRateControl|EncMiscParameterFrameRate|EncPackedHeaderParameterBuffer|CodedBufferSegment|ConfigAttrib|Image|ImageFormat|PictureH264)" \
    --allowlist-var "VA_(RT_FORMAT_YUV420|RC_CBR|RC_CQP|ENC_PACKED_HEADER_.*|STATUS_SUCCESS|INVALID_ID|INVALID_SURFACE|PICTURE_H264_.*|PROGRESSIVE|FOURCC_NV12)" \
    --allowlist-type "VA(Profile|Entrypoint|ConfigAttribType|BufferType|EncMiscParameterType|EncPackedHeaderType)" \
    --rustified-enum "VA(Profile|Entrypoint|ConfigAttribType|BufferType|EncMiscParameterType)" \
    --with-derive-default --no-layout-tests --no-doc-comments --use-core --merge-extern-blocks \
    --raw-line "// Generated by scripts/gen-va-bindings.sh from libva $version headers (MIT licence). Do not edit." \
    -o "$out" -- -I"$inc"
  rm -rf "$work"
'
