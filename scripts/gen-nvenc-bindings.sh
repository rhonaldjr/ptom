#!/usr/bin/env bash
# Regenerates crates/farsight-gpu-sys/src/nvenc/bindings.rs: Rust
# declarations for NVIDIA's video encoder API (NVENC) and the few CUDA calls
# it needs, from FFmpeg's nv-codec-headers 12.0 (NVIDIA's MIT-licensed
# headers; driver 520 or newer). The NVIDIA libraries are loaded at run
# time, so builds need neither them nor clang. Runs in the builder image.
set -euo pipefail
cd "$(dirname "$0")/.."
exec docker run --rm -u "$(id -u):$(id -g)" -v "$PWD":/w -w /w \
  -e CARGO_HOME=/w/target-docker/.cargo farsight-builder bash -euo pipefail -c '
  tag=n12.0.16.1
  sha256=37e31c7ed0c9bf2da74646a3ec426c38a6d29e60b1fb7bff3e03a99b9412e050
  work="$(mktemp -d)"
  curl -sSfL -o "$work/nv.tar.gz" "https://github.com/FFmpeg/nv-codec-headers/archive/refs/tags/$tag.tar.gz"
  echo "$sha256  $work/nv.tar.gz" | sha256sum -c --quiet
  tar -xzf "$work/nv.tar.gz" -C "$work"
  inc="$work/nv-codec-headers-$tag/include/ffnvcodec"
  printf "#include <stdint.h>\n#include \"dynlink_cuda.h\"\n#include \"nvEncodeAPI.h\"\n" > "$work/wrapper.h"
  cp "$inc"/dynlink_cuda.h "$inc"/nvEncodeAPI.h "$work/"
  bindgen=target-docker/.cargo/bin/bindgen
  [ -x "$bindgen" ] || cargo install --quiet --locked bindgen-cli --version 0.71.1
  "$bindgen" "$work/wrapper.h" \
    --dynamic-loading NvencLibrary --dynamic-link-require-all \
    --allowlist-function "NvEncodeAPI(CreateInstance|GetMaxSupportedVersion)" \
    --allowlist-type "NV_ENCODE_API_FUNCTION_LIST|NV_ENC_(OPEN_ENCODE_SESSION_EX_PARAMS|INITIALIZE_PARAMS|PRESET_CONFIG|CONFIG|CREATE_INPUT_BUFFER|CREATE_BITSTREAM_BUFFER|PIC_PARAMS|LOCK_BITSTREAM|LOCK_INPUT_BUFFER)" \
    --allowlist-type "tcu(Init|DeviceGet|CtxCreate_v2|CtxDestroy_v2|CtxPushCurrent_v2|CtxPopCurrent_v2)" \
    --allowlist-var "NVENCAPI_(MAJOR|MINOR)_VERSION|NV_ENC_SUCCESS" \
    --rustified-enum "NV_ENC_(DEVICE_TYPE|BUFFER_FORMAT|PARAMS_RC_MODE|PIC_STRUCT|MEMORY_HEAP|TUNING_INFO|PIC_TYPE|H264_ENTROPY_CODING_MODE)" \
    --with-derive-default --no-layout-tests --no-doc-comments --use-core --merge-extern-blocks \
    --raw-line "// Generated by scripts/gen-nvenc-bindings.sh from nv-codec-headers $tag (MIT licence). Do not edit." \
    -o crates/farsight-gpu-sys/src/nvenc/bindings.rs
  rm -rf "$work"
'
